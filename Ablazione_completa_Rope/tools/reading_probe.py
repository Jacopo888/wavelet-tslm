#!/usr/bin/env python3
"""Phase-A exit probe of P1-d (Astra 15/09, sentinella/P1-d D1): does the backbone READ the soft tokens?

On a fixed stratified subset of validation recordings, for one checkpoint:
  1. teacher-forced CE on the INFORMATIVE fields of the compact reading (tokens carrying digits: channel ids and bin
     indices; boilerplate excluded) under three soft-token conditions with identical prompts, headers and masks:
       TRUE        the recording's own tokens;
       SUBSTITUTED tokens of a compatible donor recording (same length and channel count; the TRUE validity mask and
                   the TRUE header are kept, so geometry, masks and header text are identical);
       ZEROED      soft tokens replaced by zeros.
     Advantage per recording = min(CE_subst, CE_zero) - CE_true; paired bootstrap over recordings.
  2. bin accuracy of the reading GENERATED by the model (thinking on) under the same three conditions: fraction of the
     teacher's (channel, bin) top/peak fields recovered, repetitions counted once.
PASS (Astra D1): mean advantage >= 0.10 nats/token with CI95 lower bound > 0 against BOTH controls, and generated bin
accuracy with TRUE tokens above both controls.  Exit code 0 on PASS, 1 otherwise; JSON report written to --out.
Never touches the test split.  Usage:
  python tools/reading_probe.py --config configs/p1dA_mi300x.toml --checkpoint <dir> --out <json> [--rows 24] [--no-generation]
"""

from __future__ import annotations

import argparse
import json
import re
import statistics as st
import sys
import time
from pathlib import Path

import numpy as np
import torch

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from safetensors.torch import load_file  # noqa: E402

from wavelet_rope.backbone import load_backbone  # noqa: E402
from wavelet_rope.checkpoint import inspect_foreign_checkpoint  # noqa: E402
from wavelet_rope.config import load_runtime_config  # noqa: E402
from wavelet_rope.data import AnomalyXLSplit, stratified_subset  # noqa: E402
from wavelet_rope.model import WRAgentModel  # noqa: E402
from wavelet_rope.templates import IGNORE_INDEX, SEG_REASONING  # noqa: E402

CONDITIONS = ("TRUE", "SUBSTITUTED", "ZEROED")
FIELD = re.compile(r"(ch_\d+):((?:\d+,?)+)")


def reading_fields(text: str) -> set[tuple[str, int]]:
    """(channel, bin) pairs named in a compact reading; repetitions collapse (Astra D2)."""

    out: set[tuple[str, int]] = set()
    for channel, bins in FIELD.findall(text or ""):
        for b in bins.split(","):
            if b:
                out.add((channel, int(b)))
    return out


def paired_bootstrap(values: list[float], seed: int, n: int = 10_000) -> dict[str, float]:
    arr = np.asarray(values, dtype=np.float64)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(arr), size=(n, len(arr)))
    means = arr[idx].mean(axis=1)
    return {"mean": float(arr.mean()), "ci95_lower": float(np.quantile(means, 0.025)),
            "ci95_upper": float(np.quantile(means, 0.975)), "n": int(len(arr)), "resamples": n}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--checkpoint", required=True, help="complete checkpoint directory")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--rows", type=int, default=24)
    ap.add_argument("--seed", type=int, default=5)
    ap.add_argument("--min-advantage", type=float, default=0.10)
    ap.add_argument("--no-generation", action="store_true")
    ap.add_argument("--max-new-tokens", type=int, default=768)
    args = ap.parse_args()
    t0 = time.time()

    cfg = load_runtime_config(args.config, validate_paths=False)
    raw, spec = cfg.as_dict(), dict(cfg.spec)
    device = torch.device("cuda:0")
    rt = raw["runtime"]
    bb = load_backbone(raw["backbone"]["snapshot"]["root"], backend=rt["attention_backend"],
                       pad_to=int(rt["attention_qk_pad_to"]), device=device, gradient_checkpointing=False)
    training = spec["training"]
    model = WRAgentModel(bb, spec, segment_weights=dict(training["segment_loss_weights"]), aux_weight=0.0)
    model.frontend.to(device); model.mixer.to(device); model.projector.to(device)
    ref = inspect_foreign_checkpoint(args.checkpoint)
    model.load_trainable_state_dict(load_file(str(ref.path / "model.safetensors")))
    bb.ctx.lam = float(ref.trainer_state["wildcard_lambda"])
    model.eval(); bb.text.eval()
    tok = bb.tokenizer

    root = Path(raw["dataset"]["root"])
    val = AnomalyXLSplit(root / raw["dataset"]["validation_relative_path"], "validation", 520)
    metas = val.metas()
    rows = stratified_subset(metas, args.rows, args.seed)
    by_row = {m.row_index: m for m in metas}

    def to_dev(ep):
        return type(ep)(ep.values.to(device), ep.valid.to(device), ep.channel_ids, ep.sample_times.to(device), ep.task)

    def donor_for(row: int):
        """Deterministic compatible donor: same length and channel count, different recording."""

        meta = by_row[row]
        candidates = [m.row_index for m in metas if m.row_index != row and m.length == meta.length
                      and len(m.channel_names) == len(meta.channel_names)]
        if not candidates:
            return None
        rng = np.random.default_rng(args.seed * 1000 + row)
        return int(rng.choice(candidates))

    orig_proj = model.projector.forward
    zero = {"on": False}

    def patched(z):
        y = orig_proj(z)
        return torch.zeros_like(y) if zero["on"] else y

    model.projector.forward = patched

    def field_positions(seq) -> torch.Tensor:
        ids, labels, seg = seq.input_ids.tolist(), seq.labels.tolist(), seq.segment.tolist()
        pos = [i - 1 for i in range(1, len(ids)) if labels[i] != IGNORE_INDEX and seg[i] == SEG_REASONING
               and re.search(r"\d", tok.decode([ids[i]]))]
        return torch.tensor(pos, dtype=torch.long)

    records = []
    with torch.no_grad(), torch.autocast("cuda", dtype=torch.bfloat16):
        for row in rows:
            meta = by_row[row]
            true_ep = to_dev(val.episode(row))
            reading = model.reading_text(true_ep, [])
            teacher_fields = reading_fields(reading)
            true_enc = model.encode_episode(true_ep, [], gold=meta.gold_intervals)
            true_header = true_enc.views[0].header
            seq = model.build_sequence(meta, true_enc, mode="direct", actions=[], answer=meta.answer,
                                       supervise_action=False, reading=reading)
            pos = field_positions(seq)
            if pos.numel() == 0:
                continue
            pos = pos.to(device)
            labels = seq.labels.to(device)
            donor_row = donor_for(row)
            donor_ep = None
            if donor_row is not None:
                d = val.episode(donor_row)
                donor_ep = type(true_ep)(d.values.to(device), true_ep.valid, true_ep.channel_ids, true_ep.sample_times, true_ep.task)
            rec = {"recording_id": meta.id, "category": meta.category, "row": row, "donor_row": donor_row,
                   "teacher_reading": reading, "ce": {}, "generated": {}, "accuracy": {}}
            for condition in CONDITIONS:
                zero["on"] = condition == "ZEROED"
                episode = donor_ep if condition == "SUBSTITUTED" else true_ep
                if condition == "SUBSTITUTED" and donor_ep is None:
                    rec["ce"][condition] = None
                    continue
                overrides = {0: true_header} if condition == "SUBSTITUTED" else None
                enc = model.encode_episode(episode, [], gold=meta.gold_intervals, header_overrides=overrides)
                embeds, is_signal, tau = model._inputs(seq, enc)
                bb.ctx.set_tokens(is_signal, tau)
                hidden = bb.text(inputs_embeds=embeds, use_cache=False).last_hidden_state[0]
                logits = bb.lm_head(hidden[pos]).float()
                rec["ce"][condition] = float(torch.nn.functional.cross_entropy(logits, labels[pos + 1]))
                if not args.no_generation:
                    gen = model.generate(meta, episode, mode="direct", max_new_tokens=args.max_new_tokens,
                                         header_overrides=overrides, thinking=True)
                    fields = reading_fields(gen.get("reading", ""))
                    rec["generated"][condition] = (gen.get("reading") or "")[:200]
                    rec["accuracy"][condition] = (len(fields & teacher_fields) / len(teacher_fields)) if teacher_fields else 0.0
            zero["on"] = False
            records.append(rec)
            print(f"[{len(records):2d}] {meta.category:24s} CE " + " ".join(
                f"{c[:4]} {rec['ce'][c]:.3f}" if rec["ce"].get(c) is not None else f"{c[:4]} n/a" for c in CONDITIONS)
                + (" | acc " + " ".join(f"{c[:4]} {rec['accuracy'].get(c, float('nan')):.2f}" for c in CONDITIONS)
                   if not args.no_generation else ""), flush=True)

    usable = [r for r in records if all(r["ce"].get(c) is not None for c in CONDITIONS)]
    adv_both = [min(r["ce"]["SUBSTITUTED"], r["ce"]["ZEROED"]) - r["ce"]["TRUE"] for r in usable]
    adv_subst = [r["ce"]["SUBSTITUTED"] - r["ce"]["TRUE"] for r in usable]
    adv_zero = [r["ce"]["ZEROED"] - r["ce"]["TRUE"] for r in usable]
    boot = {"both": paired_bootstrap(adv_both, args.seed), "vs_substituted": paired_bootstrap(adv_subst, args.seed),
            "vs_zeroed": paired_bootstrap(adv_zero, args.seed)} if usable else {}
    ce_mean = {c: st.fmean(r["ce"][c] for r in usable) for c in CONDITIONS} if usable else {}
    acc_mean = ({c: st.fmean(r["accuracy"][c] for r in usable if c in r["accuracy"]) for c in CONDITIONS}
                if usable and not args.no_generation else {})
    criteria = {
        "advantage_ge_min": bool(usable) and boot["both"]["mean"] >= args.min_advantage,
        "ci95_lower_gt_zero_vs_substituted": bool(usable) and boot["vs_substituted"]["ci95_lower"] > 0.0,
        "ci95_lower_gt_zero_vs_zeroed": bool(usable) and boot["vs_zeroed"]["ci95_lower"] > 0.0,
        "generated_accuracy_true_above_controls": (bool(acc_mean) and acc_mean["TRUE"] > max(acc_mean["SUBSTITUTED"], acc_mean["ZEROED"]))
        if not args.no_generation else None,
    }
    passed = all(v for v in criteria.values() if v is not None)
    report = {"checkpoint": str(ref.path), "optimizer_step": ref.optimizer_step, "rows": len(usable), "seed": args.seed,
              "min_advantage": args.min_advantage, "ce_mean": ce_mean, "bootstrap": boot, "generated_accuracy_mean": acc_mean,
              "criteria": criteria, "verdict": "PASS" if passed else "FAIL", "seconds": round(time.time() - t0, 1),
              "records": records}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
    print(f"READING_PROBE step {ref.optimizer_step}: CE {ce_mean} | advantage both {boot.get('both')} | "
          f"acc {acc_mean} | criteria {criteria} | VERDICT {report['verdict']} ({report['seconds']}s)")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
